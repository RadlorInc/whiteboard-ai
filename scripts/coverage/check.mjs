// Library coverage against the US topic checklist (topics.json; founder, 19 Oct 2026: US market first).
//   node scripts/coverage/check.mjs      -> scripts/coverage/report.md, and a one-line summary per subject
// A topic is covered when one of its keys is a recipe name in that subject's prompt categories, or a word inside the id
// of a realistic drawing the subject's search covers, matched as whole hyphen-separated words ("bell" must not match
// the bell emoji's id only by luck: keys are whole words of the id, "ngs" is not "lungs").
import fs from 'node:fs';
import path from 'node:path';
import { WB_LIB } from '../../src/lib/generation/checks.mjs';
import P from '../../src/lib/generation/prompts.json' with { type: 'json' };

const here = path.dirname(new URL(import.meta.url).pathname);
const T = JSON.parse(fs.readFileSync(path.join(here, 'topics.json'), 'utf8'));
const out = ['# Library coverage (US checklist)', '', `Generated by scripts/coverage/check.mjs from topics.json.`, ''];
const summary = [];
for (const s of ['biology', 'physics', 'chemistry']) {
  const cats = P.subjects[s].cats, lib = WB_LIB.filter(c => cats.includes(c.cat));
  const recipes = new Set(lib.filter(c => !c.cat.startsWith('servier')).flatMap(c => c.lines.map(l => l.name)));
  const sv = lib.filter(c => c.cat.startsWith('servier')).flatMap(c => c.lines.map(l => l.name));
  const rows = T[s].map(x => { const hit = x.key.map(k => recipes.has(k) ? k : (sv.find(id => `-${id}-`.includes(`-${k}-`)) || null)).find(Boolean);
    return { ...x, hit }; });
  const done = rows.filter(r => r.hit).length;
  summary.push(`${s}: ${done}/${rows.length} covered`);
  out.push(`## ${s[0].toUpperCase() + s.slice(1)}: ${done} of ${rows.length}`, '', '| Topic | Level | Drawing |', '|---|---|---|',
    ...rows.map(r => `| ${r.t} | ${r.lvl} | ${r.hit ? '`' + r.hit + '`' : '**missing**'} |`), '');
}
fs.writeFileSync(path.join(here, 'report.md'), out.join('\n'));
console.log(summary.join('\n'));
for (const s of ['biology', 'physics', 'chemistry']) {
  const miss = out.join('\n').split(`## ${s[0].toUpperCase() + s.slice(1)}`)[1].split('\n## ')[0].split('\n').filter(l => l.includes('**missing**')).map(l => l.split(' | ')[0].slice(2));
  console.log(`\n${s} missing (${miss.length}): ${miss.join('; ')}`);
}
